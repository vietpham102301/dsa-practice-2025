const INF = math.MaxInt32 / 2

func HeldKarpTSP(dist [][]int) int {
	n := len(dist)
	if n == 0 {
		return 0
	}

	// 2^n trạng thái
	maxMask := 1 << n

	dp := make([][]int, maxMask)
	for i := range dp {
		dp[i] = make([]int, n)
		for j := range dp[i] {
			dp[i][j] = INF
		}
	}

	dp[1][0] = 0 // Đỉnh bắt đầu là 0, tập S đang xét bật bit ngoài cùng bên phải ...00001

	// Do đỉnh bắt đầu là 0 và mọi con đường xét phải chứa nó nên chỉ xét các mask là số lẻ <=> bit cuối luôn được bật
	for mask := 1; mask < maxMask; mask += 2 {
		// Duyệt các đỉnh j tiếp theo
		for j := 1; j < n; j++ {
			if (mask & (1 << j)) != 0 { // Đỉnh j có trong tập đang xét
				prevMask := mask ^ (1 << j) // Tắt bit này
				for i := 0; i < n; i++ {
					if (prevMask & (1 << i)) != 0 { // Đỉnh i có trong tập đang xét
						if dp[prevMask][i]+dist[i][j] < dp[mask][j] {
							dp[mask][j] = dp[prevMask][i] + dist[i][j] // Cập nhật đường đi tối ưu hơn
						}
					}
				}
			}
		}
	}

	minTour := INF
	fullMask := maxMask - 1

	for j := 1; j < n; j++ {
		if dp[fullMask][j]+dist[j][0] < minTour {
			minTour = dp[fullMask][j] + dist[j][0]
		}
	}

	return minTour
}

